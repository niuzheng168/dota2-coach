import assert from 'node:assert/strict';
import { once } from 'node:events';
import fs from 'node:fs/promises';
import { createSandboxServer } from '../src/sandbox/server.ts';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const { server, token } = createSandboxServer();
server.listen(0, '127.0.0.1'); await once(server, 'listening');
const origin = `http://127.0.0.1:${server.address().port}`;
const browser = await chromium.launch({ headless: true, executablePath: process.env.PLAYWRIGHT_EXECUTABLE_PATH });
try {
  const page = await browser.newPage({ viewport: { width: 1360, height: 1100 } }), errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.route('**/*', r => new URL(r.request().url()).origin === origin ? r.continue() : r.abort());
  await page.goto(`${origin}/map-audit#token=${token}`);
  await page.waitForFunction(() => document.querySelector('#status').textContent.includes('已载入原始回放'));
  assert.equal(new URL(page.url()).hash, '');
  assert.equal(await page.locator('#match option').count(), 3);
  assert.equal(await page.locator('#camp option').count(), 28);
  assert.ok((await page.locator('#camp-status').textContent()).includes('6 个实际存活单位'));
  assert.ok((await page.locator('#checks').textContent()).includes('防御塔 22/22'));
  assert.equal(await page.locator('#checks li.pass').count(), 7);
  assert.ok((await page.locator('#client-mechanics').textContent()).includes('392.2'));
  await page.locator('#time').fill('18');
  await page.locator('#time').dispatchEvent('input');
  assert.equal(await page.locator('#clock').textContent(), '11:30');
  await page.locator('#old-lanes').check();
  await page.locator('#trees').check();
  await page.locator('#grid-diff').check();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await fs.mkdir('.tmp', { recursive: true });
  await page.screenshot({ path: '.tmp/map-audit-comparison.png', fullPage: true });
  await page.locator('#old-lanes').uncheck();
  await page.locator('#trees').uncheck();
  await page.locator('#match').selectOption('9090701002');
  assert.ok((await page.locator('#match option:checked').textContent()).includes('Pure'));
  await page.locator('#time').fill('18'); await page.locator('#time').dispatchEvent('input');
  await page.screenshot({ path: '.tmp/map-audit-preview.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 }); await page.waitForTimeout(100);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  assert.deepEqual(errors, []);
  console.log('PASS map audit browser: default evidence view, 3 real matches, 28 camps, actual unit counts, layers, timeline, mobile.');
} finally { await browser.close(); await new Promise(resolve => server.close(resolve)); }
